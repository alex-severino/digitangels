/** Pours the bands when the card comes into view and again on each hover. */
export function DvorPour({ className = "" }: { className?: string }) {
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const pour = () => {
      el.classList.remove("is-pouring");
      void el.offsetWidth;
      el.classList.add("is-pouring");
    };
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry?.isIntersecting) {
          pour();
          io.disconnect();
        }
      },
      { threshold: 0.4 },
    );
    io.observe(el);
    const card = el.closest("a") ?? el;
    card.addEventListener("pointerenter", pour);
    return () => {
      io.disconnect();
      card.removeEventListener("pointerenter", pour);
    };
  }, []);

  return (
    <div
      ref={ref}
      role="img"
      aria-label="Dvor wordmark over five painted bands and a concrete panel grid"
      className={`dt-pour relative isolate overflow-hidden bg-[#b8b7b7] ${className}`}
    >
      {BANDS.map((band, i) => (
        <div key={band.fill} className="dt-pour-band absolute inset-0" style={{ "--i": i } as React.CSSProperties}>
          <Layer>
            <path d={band.d} fill={band.fill} />
          </Layer>
        </div>
      ))}
      <div className="absolute inset-0 mix-blend-multiply">
        <Layer>
          <g fill="#8d8d8d">
            <rect x="179.38" width="6" height="1080" />
            <rect x="957" width="6" height="1080" />
            <rect x="1734.62" width="6" height="1080" />
            <rect y="146.75" width="1920" height="6" />
            <rect y="924.37" width="1920" height="6" />
          </g>
        </Layer>
      </div>
      <Layer>
        <defs>
          <filter id="dvor-pour-shadow" x="-5%" y="-20%" width="110%" height="140%">
            <feDropShadow dx="0.7" dy="4.5" stdDeviation="2" floodColor="#000" floodOpacity="0.5" />
          </filter>
        </defs>
        <path d={LOGO} transform={LOGO_TRANSFORM} fill="#fff" filter="url(#dvor-pour-shadow)" />
      </Layer>
    </div>
  );
}
